/**
 * Find detailed material source by itemId or name
 */
export function getMaterialSource(itemId: number, name?: string): DetailedMaterialSource | undefined {
  if (MATERIAL_SOURCE_REGISTRY[itemId]) {
    return MATERIAL_SOURCE_REGISTRY[itemId];
  }
  if (name) {
    const found = Object.values(MATERIAL_SOURCE_REGISTRY).find((item) => item.name === name);
    if (found) return found;
  }
  return undefined;
}
